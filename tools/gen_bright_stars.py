#!/usr/bin/env python3
"""Writes core/domain/.../sky/BrightStars.kt from the Yale Bright Star Catalogue, 5th edition
(Hoffleit & Warren 1991, public domain, http://tdc-www.harvard.edu/catalogs/bsc5.html): every
star brighter than the limit, with its J2000 right ascension and declination, its visual
magnitude and its B-V colour. The canvas draws them where they stand (DESIGN §3.9, step 6 of
the sky review, 19 ott 2026).

    python tools/gen_bright_stars.py [path/to/bsc5.dat.gz]

Without a path the catalogue is downloaded next to this script. The generated file is the
drawing: change this script and run it again, never the Kotlin.
"""
import gzip
import os
import sys
import urllib.request

LIMIT_MAG = 4.5
URL = "http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz"
OUT = os.path.join(os.path.dirname(__file__), "..", "core", "domain", "src", "main", "kotlin",
                   "com", "callbackdev", "chiaro", "domain", "sky", "BrightStars.kt")


def load(path):
    if not os.path.exists(path):
        print("downloading", URL)
        urllib.request.urlretrieve(URL, path)
    with gzip.open(path, "rb") as f:
        return f.read().decode("latin-1").splitlines()


def parse(lines):
    """The fixed columns of the catalogue's ReadMe (1-based): RA J2000 at 76-83 (h, m, s.s),
    Dec J2000 at 84-90 (sign, deg, arcmin, arcsec), Vmag at 103-107, B-V at 110-114."""
    stars = []
    for line in lines:
        ra, dec, vmag, bv = line[75:83], line[83:90], line[102:107].strip(), line[109:114].strip()
        if not ra.strip() or not vmag:
            continue  # a nova or a duplicate with no position
        mag = float(vmag)
        if mag > LIMIT_MAG:
            continue
        h, m, s = int(ra[0:2]), int(ra[2:4]), float(ra[4:8])
        ra_deg = 15.0 * (h + m / 60.0 + s / 3600.0)
        sign = -1.0 if dec[0] == "-" else 1.0
        d, dm, ds = int(dec[1:3]), int(dec[3:5]), int(dec[5:7])
        dec_deg = sign * (d + dm / 60.0 + ds / 3600.0)
        colour = float(bv) if bv else 0.0
        stars.append((ra_deg, dec_deg, mag, colour))
    stars.sort(key=lambda s: s[2])
    return stars


def kotlin_array(name, values, fmt):
    rows = []
    for i in range(0, len(values), 8):
        rows.append("        " + ", ".join(fmt % v for v in values[i:i + 8]) + ",")
    return "    val %s: FloatArray = floatArrayOf(\n%s\n    )\n" % (name, "\n".join(rows))


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "bsc5.dat.gz")
    stars = parse(load(path))
    brightest = stars[0]
    body = (
        "package com.callbackdev.chiaro.domain.sky\n\n"
        "/**\n"
        " * The stars the canvas draws where they stand (DESIGN §3.9, step 6 of the sky review,\n"
        " * 19 ott 2026): every star of the Yale Bright Star Catalogue, 5th edition (Hoffleit &\n"
        " * Warren 1991), brighter than magnitude %.1f, sorted brightest first. J2000 right ascension\n"
        " * and declination in degrees, visual magnitude, B-V colour (0 where the catalogue has\n"
        " * none). Precession since J2000 moves a star by about a third of a degree, under what a\n"
        " * dp of the canvas holds, and is not applied.\n"
        " *\n"
        " * GENERATED by `tools/gen_bright_stars.py`: re-running the tool is the edit, never this file.\n"
        " */\n"
        "object BrightStars {\n"
        "    const val LIMIT_MAG = %.1ff\n"
        "    val count: Int get() = mag.size\n\n"
    ) % (LIMIT_MAG, LIMIT_MAG)
    body += kotlin_array("raDeg", [s[0] for s in stars], "%.4ff")
    body += "\n" + kotlin_array("decDeg", [s[1] for s in stars], "%.4ff")
    body += "\n" + kotlin_array("mag", [s[2] for s in stars], "%.2ff")
    body += "\n" + kotlin_array("bv", [s[3] for s in stars], "%.2ff")
    body += "}\n"
    with open(os.path.normpath(OUT), "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("wrote", os.path.normpath(OUT), len(stars), "stars; brightest", brightest)


if __name__ == "__main__":
    main()
